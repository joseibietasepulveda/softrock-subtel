class Connection(psycopg.Connection):
    """Conexión Postgres que acepta los placeholders `?` del código y devuelve filas dict."""

    def execute(self, query, params=None, **kw):
        return super().execute(query.replace("?", "%s") if isinstance(query, str) else query, params, **kw)


def db() -> Connection:
    # Cada operación abre su propia conexión; no se comparten conexiones entre hilos.
    if not DATABASE_URL:
        raise RuntimeError("Configure DATABASE_URL con la conexión a PostgreSQL de este ambiente")
    return Connection.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=10)


