# Si Keycloak asigna más de un rol, gana el de más privilegio.
ROLE_PRIORITY = ("administrador", "auditor", "aprobador", "revisor", "operador", "regular")
_oidc_meta_cache: dict = {}


def oidc_enabled() -> bool:
    return bool(os.environ.get("OIDC_ISSUER") and os.environ.get("OIDC_CLIENT_ID"))


def _http_json(url: str, data: dict | None = None) -> dict:
    import urllib.parse
    import urllib.request
    body = urllib.parse.urlencode(data).encode() if data is not None else None
    with urllib.request.urlopen(urllib.request.Request(url, data=body, headers={"Accept": "application/json"}),
                                timeout=10) as r:
        return json.loads(r.read())


def oidc_meta() -> dict:
    if not _oidc_meta_cache:
        _oidc_meta_cache.update(_http_json(os.environ["OIDC_ISSUER"].rstrip("/") + "/.well-known/openid-configuration"))
    return _oidc_meta_cache


def _jwt_claims(token: str) -> dict:
    import base64
    payload = token.split(".")[1]
    return json.loads(base64.urlsafe_b64decode(payload + "=" * (-len(payload) % 4)))


def oidc_user(tokens: dict, nonce: str) -> dict:
    """Valida el id_token y resuelve usuario y rol. Lanza ValueError con el motivo si no corresponde.

    Los tokens se obtienen directamente del endpoint de Keycloak por TLS en el
    flujo authorization code. Se comprueban issuer, audience, nonce y expiración;
    no se verifica localmente la firma JWT. Esta función no acepta tokens del
    navegador ni habilita tokens Bearer de Keycloak en los endpoints de la API.
    """
    client_id = os.environ["OIDC_CLIENT_ID"]
    idt = _jwt_claims(tokens["id_token"])
    aud = idt.get("aud")
    if idt.get("iss") != oidc_meta()["issuer"]:
        raise ValueError("issuer inesperado")
    if client_id not in (aud if isinstance(aud, list) else [aud]):
        raise ValueError("audience inesperada")
    if not hmac.compare_digest(str(idt.get("nonce", "")), nonce):
        raise ValueError("nonce inválido")
    if idt.get("exp", 0) < time.time():
        raise ValueError("id_token vencido")
    # Keycloak pone los roles en el access_token; se leen de ahí y, por si hay mapper, del id_token.
    roles: set[str] = set()
    for claims in (idt, _jwt_claims(tokens["access_token"]) if tokens.get("access_token") else {}):
        roles.update(claims.get("resource_access", {}).get(client_id, {}).get("roles", []))
        roles.update(claims.get("realm_access", {}).get("roles", []))
    # SUBTEL puede nombrar sus roles como quiera y tener cuantos quiera: OIDC_ROLE_MAP traduce cada uno
    # a un perfil de permisos de la plataforma, ej. {"abogado-dj": "revisor", "jefatura-dj": "aprobador"}.
    role_map = json.loads(os.environ.get("OIDC_ROLE_MAP", "{}"))
    roles = {role_map.get(r, r) for r in roles}
    role = next((r for r in ROLE_PRIORITY if r in roles), None) or os.environ.get("OIDC_DEFAULT_ROLE", "")
    if role not in ROLES:
        raise ValueError("sin rol asignado en Keycloak")
    username = (idt.get("preferred_username") or idt.get("email") or idt["sub"]).strip().lower()
    return {"username": username, "display_name": idt.get("name") or username, "role": role}


def audit(con: Connection, username: str, ip: str | None, event: str, details: dict):
    """Registra un evento en la cadena de hashes.

    El advisory lock se toma ANTES de leer el último hash, de modo que dos escritores
    concurrentes (hilos o procesos web distintos) no puedan encadenar sobre el mismo
    `prev_hash` y romper la cadena. Postgres hace esperar al segundo hasta el commit.
    """
    ts = now()
    d = json.dumps(details, ensure_ascii=False, sort_keys=True)
    con.commit()  # cierra la transacción implícita del llamador antes de abrir la propia
    con.execute("SELECT pg_advisory_xact_lock(?)", (LOCK_AUDIT,))
    prev = con.execute("SELECT hash FROM audit_log ORDER BY id DESC LIMIT 1").fetchone()
    prev_hash = prev["hash"] if prev else "0" * 64
    h = hashlib.sha256(f"{prev_hash}|{ts}|{username}|{ip}|{event}|{d}".encode()).hexdigest()
    con.execute("INSERT INTO audit_log(ts,username,ip,event,details,prev_hash,hash) VALUES(?,?,?,?,?,?,?)",
                (ts, username, ip, event, d, prev_hash, h))
    con.commit()


