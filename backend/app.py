@app.post("/api/auth/login")
async def login(request: Request, response: Response, body: dict):
    username = body.get("username", "").strip().lower()
    con = db()
    try:
        ldap_user = ldap_authenticate(username, body.get("password", ""))
        if ldap_user:
            con.execute("INSERT INTO users(username,display_name,role,password_hash,auth_source,created_at) VALUES(?,?,?,?,?,?) "
                        "ON CONFLICT(username) DO UPDATE SET display_name=excluded.display_name, role=excluded.role",
                        (username, ldap_user["display_name"], ldap_user["role"], "", "ldap", now()))
            con.commit()
        row = con.execute("SELECT * FROM users WHERE username=? AND active=1", (username,)).fetchone()
        if not row or (not ldap_user and not check_password(body.get("password", ""), row["password_hash"])):
            audit(con, username or "?", ip_of(request), "login_failed", {})
            raise HTTPException(401, "Usuario o contraseña incorrectos")
        start_session(con, request, response, row)
        return {"username": row["username"], "display_name": row["display_name"], "role": row["role"]}
    finally:
        con.close()


def start_session(con: Connection, request: Request, response: Response, row, details: dict | None = None):
    tok = secrets.token_urlsafe(32)
    con.execute("INSERT INTO sessions VALUES(?,?,?)", (tok, row["id"], time.time() + SESSION_TTL))
    con.execute("UPDATE users SET last_login_at=? WHERE id=?", (now(), row["id"]))
    con.execute("DELETE FROM sessions WHERE expires<?", (time.time(),))
    audit(con, row["username"], ip_of(request), "login", details or {})
    response.set_cookie("session", tok, httponly=True, samesite="lax", max_age=SESSION_TTL)


