@app.get("/api/auth/oidc/login")
async def oidc_login(request: Request):
    import base64
    import urllib.parse
    from fastapi.responses import RedirectResponse
    if not oidc_enabled():
        raise HTTPException(404, "Keycloak no está configurado")
    state, nonce, verifier = (secrets.token_urlsafe(32) for _ in range(3))
    challenge = base64.urlsafe_b64encode(hashlib.sha256(verifier.encode()).digest()).rstrip(b"=").decode()
    q = urllib.parse.urlencode({"response_type": "code", "client_id": os.environ["OIDC_CLIENT_ID"],
                                "redirect_uri": _oidc_redirect_uri(request), "scope": "openid profile email",
                                "state": state, "nonce": nonce,
                                "code_challenge": challenge, "code_challenge_method": "S256"})
    resp = RedirectResponse(oidc_meta()["authorization_endpoint"] + "?" + q, status_code=302)
    resp.set_cookie("oidc_tx", f"{state}.{nonce}.{verifier}", httponly=True, samesite="lax", max_age=600,
                    path="/api/auth/oidc")
    return resp


@app.get("/api/auth/oidc/callback", name="oidc_callback")
async def oidc_callback(request: Request, code: str = "", state: str = "", error: str = ""):
    from fastapi.responses import RedirectResponse
    state_c, nonce, verifier = (request.cookies.get("oidc_tx", "").split(".") + ["", "", ""])[:3]
    con = db()
    try:
        try:
            if error or not code:
                raise ValueError(error or "sin código de autorización")
            if not state_c or not hmac.compare_digest(state, state_c):
                raise ValueError("state inválido")
            data = {"grant_type": "authorization_code", "code": code, "redirect_uri": _oidc_redirect_uri(request),
                    "client_id": os.environ["OIDC_CLIENT_ID"], "code_verifier": verifier}
            if os.environ.get("OIDC_CLIENT_SECRET"):
                data["client_secret"] = os.environ["OIDC_CLIENT_SECRET"]
            info = oidc_user(_http_json(oidc_meta()["token_endpoint"], data), nonce)
        except Exception as e:  # noqa: BLE001 — cualquier falla termina en la pantalla de login con el motivo auditado
            audit(con, "?", ip_of(request), "login_failed", {"origen": "keycloak", "motivo": str(e)[:200]})
            resp = RedirectResponse("/?login_error=keycloak", status_code=302)
            resp.delete_cookie("oidc_tx", path="/api/auth/oidc")
            return resp
        # El rol lo manda Keycloak en cada ingreso: un cambio hecho ahí se refleja al siguiente login.
        con.execute("INSERT INTO users(username,display_name,role,password_hash,auth_source,created_at) VALUES(?,?,?,?,?,?) "
                    "ON CONFLICT(username) DO UPDATE SET display_name=excluded.display_name, role=excluded.role",
                    (info["username"], info["display_name"], info["role"], "", "keycloak", now()))
        con.commit()
        row = con.execute("SELECT * FROM users WHERE username=?", (info["username"],)).fetchone()
        resp = RedirectResponse("/", status_code=302)
        resp.delete_cookie("oidc_tx", path="/api/auth/oidc")
        if not row["active"]:  # desactivado localmente por un administrador: manda sobre Keycloak
            audit(con, row["username"], ip_of(request), "login_failed", {"origen": "keycloak", "motivo": "usuario inactivo"})
            resp.headers["location"] = "/?login_error=inactivo"
            return resp
        start_session(con, request, resp, row, {"origen": "keycloak"})
        return resp
    finally:
        con.close()


@app.post("/api/auth/logout")
async def logout(request: Request, response: Response, user=Depends(current_user)):
    import urllib.parse
    con = db()
    con.execute("DELETE FROM sessions WHERE token=?", (request.cookies.get("session"),))
    src = con.execute("SELECT auth_source FROM users WHERE id=?", (user["id"],)).fetchone() if user["id"] else None
    audit(con, user["username"], ip_of(request), "logout", {})
    con.close()
    response.delete_cookie("session")
    out: dict = {"ok": True}
    # Sin esto, "Salir" deja viva la sesión de Keycloak y el siguiente clic vuelve a entrar sin pedir clave.
    if src and src["auth_source"] == "keycloak" and oidc_enabled() and oidc_meta().get("end_session_endpoint"):
        back = str(request.base_url) if not os.environ.get("OIDC_REDIRECT_URI") else \
            os.environ["OIDC_REDIRECT_URI"].split("/api/")[0] + "/"
        out["logout_url"] = oidc_meta()["end_session_endpoint"] + "?" + urllib.parse.urlencode(
            {"client_id": os.environ["OIDC_CLIENT_ID"], "post_logout_redirect_uri": back})
    return out


