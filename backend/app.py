def choice(value: str, options: dict[str, str], error: str) -> str:
    """Acepta el código de la API (`balanced`) o el nombre que muestra la plataforma
    (`Equilibrado`, con o sin tilde), para que un cliente de API elija lo mismo que un usuario."""
    v = (value or "").strip().lower()
    for code, label in options.items():
        if v == code or pipeline._norm_soft(v) == pipeline._norm_soft(label):
            return code
    raise HTTPException(422, error)


def resolve_options(con, document_type: str, entities: list[str], treatment: str, analysis_level: str) -> dict:
    """Valida las opciones que elige un usuario en la plataforma; sin `entities` rige la política del tipo."""
    from .documents import effective_entities  # import diferido: documents importa este módulo
    if not con.execute("SELECT 1 FROM document_types WHERE code=? AND active=1", (document_type,)).fetchone():
        raise HTTPException(400, "Tipo documental inválido")
    return {"document_type": document_type,
            "entities": [c for c in entities if c in engine.ENTITY_TYPES] or effective_entities(con, document_type),
            "treatment": choice(treatment, pipeline.TREATMENTS, "Tratamiento inválido"),
            "analysis_level": choice(analysis_level, pipeline.ANALYSIS_LEVELS, "Nivel de análisis inválido")}


def _opts(options: dict[str, str]) -> str:
    return " | ".join(f"{c} ({l})" for c, l in options.items())


ENTITIES_HELP = ("Códigos separados por coma (GET /api/v1/entity-types). Vacío = política del tipo documental.")
DOCUMENT_TYPE_HELP = "Tipo documental (GET /api/document-types); define la política de datos a buscar."
ANALYSIS_HELP = "Nivel de análisis: " + _opts(pipeline.ANALYSIS_LEVELS)


@app.post("/api/v1/redact", summary="Protege un documento y devuelve el archivo en el mismo formato",
          description="Procesamiento directo sin revisión humana. Los PDF se entregan como PDF/A-1b.")
async def redact(request: Request, file: UploadFile = File(...),
                 entities: str = Form("", description=ENTITIES_HELP),
                 document_type: str = Form("otro", description=DOCUMENT_TYPE_HELP),
                 treatment: str = Form("redact", description="Tratamiento: " + _opts(pipeline.TREATMENTS)),
                 analysis_level: str = Form("fast", description=ANALYSIS_HELP),
                 user=Depends(require("operador", "revisor", "aprobador", "administrador"))):
    con = db()
    try:
        opts = resolve_options(con, document_type, entities.split(","), treatment, analysis_level)
    finally:
        con.close()
    codes, treatment, analysis_level = opts["entities"], opts["treatment"], opts["analysis_level"]
    name = Path(file.filename or "documento").name
    ext = Path(name).suffix.lower()
    if ext not in engine.SUPPORTED:
        raise HTTPException(415, f"Formato no soportado: {ext or 'sin extensión'}")
    tmp = Path(tempfile.mkdtemp(prefix="tachado_"))
    src, dst = tmp / ("in" + ext), tmp / (Path(name).stem + "_protegido" + ext)
    size = 0
    with src.open("wb") as fh:
        while chunk := await file.read(1024 * 1024):
            size += len(chunk)
            if size > MAX_UPLOAD:
                raise HTTPException(413, f"Archivo supera el máximo de {MAX_UPLOAD // 1024 // 1024} MB")
            fh.write(chunk)
    sha = hashlib.sha256(src.read_bytes()).hexdigest()
    t0 = time.time()
    con = db()
    try:
        stats, verification = pipeline.protect(src, dst, tmp / "work", codes, treatment, analysis_level)
        if not verification["ok"]:
            raise engine.EngineError("VERIFY_FAILED", "La verificación detectó datos originales en el resultado")
    except engine.EngineError as e:
        audit(con, user["username"], ip_of(request), "process_failed",
              {"file": name, "sha256": sha, "analysis_level": analysis_level, "error": e.code})
        con.close()
        raise HTTPException(422 if e.code != "UNSUPPORTED_FORMAT" else 415, str(e))
    except Exception as e:  # noqa: BLE001
        audit(con, user["username"], ip_of(request), "process_failed",
              {"file": name, "sha256": sha, "analysis_level": analysis_level, "error": "INTERNAL"})
        con.close()
        raise HTTPException(500, f"Error al procesar el documento: {type(e).__name__}")
    stats["seconds"] = round(time.time() - t0, 2)
    stats["analysis_level"] = analysis_level
    audit(con, user["username"], ip_of(request), "protected",
          {"file": name, "sha256": sha, "entities": codes, "document_type": document_type,
           "treatment": treatment, "analysis_level": analysis_level, "stats": stats})
    con.close()
    return FileResponse(dst, filename=dst.name, media_type="application/octet-stream",
                        headers={"X-Tachado-Stats": json.dumps(stats, ensure_ascii=True)},
                        background=BackgroundTask(lambda: __import__("shutil").rmtree(tmp, ignore_errors=True)))


