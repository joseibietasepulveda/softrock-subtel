def _validate_password(pw: str):
    if len(pw) < 10 or not any(c.isupper() for c in pw) or not any(c.isdigit() for c in pw):
        raise HTTPException(400, "La contraseña debe tener al menos 10 caracteres, una mayúscula y un número")


@app.post("/api/users", status_code=201)
async def create_user(request: Request, body: dict, user=Depends(require("administrador"))):
    username = body.get("username", "").strip().lower()
    if not username.isidentifier():
        raise HTTPException(400, "Nombre de usuario inválido (letras, números y guion bajo)")
    if body.get("role") not in ROLES:
        raise HTTPException(400, "Rol inválido")
    _validate_password(body.get("password", ""))
    con = db()
    try:
        con.execute("INSERT INTO users(username,display_name,role,password_hash,created_at) VALUES(?,?,?,?,?)",
                    (username, body.get("display_name") or username, body["role"], hash_password(body["password"]), now()))
    except psycopg.errors.UniqueViolation:
        con.close()
        raise HTTPException(409, "El usuario ya existe")
    audit(con, user["username"], ip_of(request), "user_created", {"username": username, "role": body["role"]})
    con.close()
    return {"ok": True}


@app.patch("/api/users/{uid}")
async def update_user(request: Request, uid: int, body: dict, user=Depends(require("administrador"))):
    con = db()
    row = con.execute("SELECT * FROM users WHERE id=?", (uid,)).fetchone()
    if not row:
        con.close()
        raise HTTPException(404, "Usuario no existe")
    changes = {}
    if "role" in body:
        if body["role"] not in ROLES:
            raise HTTPException(400, "Rol inválido")
        con.execute("UPDATE users SET role=? WHERE id=?", (body["role"], uid)); changes["role"] = body["role"]
    if "active" in body:
        if uid == user["id"] and not body["active"]:
            raise HTTPException(400, "No puedes desactivarte a ti mismo")
        con.execute("UPDATE users SET active=? WHERE id=?", (1 if body["active"] else 0, uid)); changes["active"] = bool(body["active"])
        if not body["active"]:
            con.execute("DELETE FROM sessions WHERE user_id=?", (uid,))
    if "display_name" in body:
        con.execute("UPDATE users SET display_name=? WHERE id=?", (body["display_name"], uid)); changes["display_name"] = body["display_name"]
    if body.get("password"):
        _validate_password(body["password"])
        con.execute("UPDATE users SET password_hash=? WHERE id=?", (hash_password(body["password"]), uid)); changes["password"] = "cambiada"
    audit(con, user["username"], ip_of(request), "user_updated", {"username": row["username"], **changes})
    con.close()
    return {"ok": True}


