@app.get("/api/audit")
async def get_audit(request: Request, event: str = "", username: str = "", limit: int = 500, format: str = "json",
                    user=Depends(require("auditor", "administrador"))):
    con = db()
    q, args = "SELECT * FROM audit_log WHERE 1=1", []
    if event:
        q += " AND event=?"; args.append(event)
    if username:
        q += " AND username LIKE ?"; args.append(f"%{username}%")
    q += " ORDER BY id DESC LIMIT ?"; args.append(min(limit, 5000))
    rows = [dict(r) for r in con.execute(q, args)]
    title_cache: dict[str, str | None] = {}
    analysis_cache: dict[str, str] = {}
    for row in rows:
        row["treatment"] = ""
        row["analysis_level"] = ""
        try:
            detail = json.loads(row["details"])
        except (TypeError, json.JSONDecodeError):
            continue
        if isinstance(detail, dict):
            row["treatment"] = detail.get("treatment") or (detail.get("stats") or {}).get("treatment") or ""
            row["analysis_level"] = (detail.get("analysis_level")
                                     or (detail.get("stats") or {}).get("analysis_level") or "")
        if isinstance(detail, dict) and "document_id" in detail:
            doc_id = str(detail.pop("document_id"))
            title = detail.pop("file", None)
            if not title or not row["analysis_level"]:
                if doc_id not in title_cache or doc_id not in analysis_cache:
                    found = con.execute(
                        "SELECT original_name, analysis_level FROM documents WHERE id=?", (doc_id,)
                    ).fetchone()
                    title_cache[doc_id] = found["original_name"] if found else None
                    analysis_cache[doc_id] = (found["analysis_level"] if found else "") or "fast"
            if not title:
                title = title_cache[doc_id]
            if not row["analysis_level"]:
                row["analysis_level"] = analysis_cache.get(doc_id, "")
            detail["documento"] = title or "Documento eliminado"
        if isinstance(detail, dict) and "ids" in detail and "files" in detail:
            detail.pop("ids", None)
            detail["documentos"] = detail.pop("files")
        row["details"] = json.dumps(detail, ensure_ascii=False, sort_keys=True)
    con.close()
    if format == "csv":
        buf = io.StringIO()
        w = csv.DictWriter(buf, fieldnames=["id", "ts", "username", "ip", "event", "treatment",
                                            "analysis_level", "details", "prev_hash", "hash"])
        w.writeheader(); w.writerows(rows)
        return StreamingResponse(iter([buf.getvalue()]), media_type="text/csv",
                                 headers={"Content-Disposition": "attachment; filename=bitacora.csv"})
    return rows


@app.get("/api/audit/verify")
async def verify_audit(user=Depends(require("auditor", "administrador"))):
    """Recorre la cadena de hashes y confirma que nadie alteró la bitácora."""
    con = db()
    prev = "0" * 64
    for r in con.execute("SELECT * FROM audit_log ORDER BY id"):
        expected = hashlib.sha256(f"{prev}|{r['ts']}|{r['username']}|{r['ip']}|{r['event']}|{r['details']}".encode()).hexdigest()
        if r["prev_hash"] != prev or r["hash"] != expected:
            con.close()
            return {"ok": False, "broken_at": r["id"]}
        prev = r["hash"]
    con.close()
    return {"ok": True}


