# ---------------------------------------------------------------------------
# LDAP / Active Directory (FR-91): bind de servicio → búsqueda → bind del usuario.
# Fallback a usuarios locales si está deshabilitado o el usuario no existe en el directorio.
# ---------------------------------------------------------------------------

def ldap_authenticate(username: str, password: str) -> dict | None:
    if os.environ.get("LDAP_ENABLED", "").lower() not in ("1", "true", "yes") or not password:
        return None
    try:
        from ldap3 import Connection, Server
        from ldap3.utils.conv import escape_filter_chars
        server = Server(os.environ["LDAP_URL"], connect_timeout=5)
        attr = os.environ.get("LDAP_USER_ATTR", "sAMAccountName")
        with Connection(server, os.environ.get("LDAP_BIND_DN"), os.environ.get("LDAP_BIND_PASSWORD"),
                        auto_bind=True, receive_timeout=10) as c:
            c.search(os.environ["LDAP_BASE_DN"], f"({attr}={escape_filter_chars(username)})",
                     attributes=["displayName", "memberOf"])
            if not c.entries:
                return None
            entry = c.entries[0]
            dn = entry.entry_dn
            display = str(entry.displayName) if entry.displayName else username
            groups = [str(g).lower() for g in (entry.memberOf or [])]
        with Connection(server, dn, password, auto_bind=True):  # valida la contraseña
            pass
        role_map = json.loads(os.environ.get("LDAP_GROUP_ROLE_MAP", "{}"))
        role = next((r for g, r in role_map.items() if g.lower() in groups and r in ROLES), None) \
            or os.environ.get("LDAP_DEFAULT_ROLE", "")
        if role not in ROLES:
            return None  # sin grupo mapeado → sin acceso
        return {"display_name": display, "role": role}
    except KeyError as e:
        raise RuntimeError(f"LDAP_ENABLED=1 pero falta la variable {e}")
    except Exception:  # noqa: BLE001 — credencial inválida o directorio caído → fallback local
        return None


