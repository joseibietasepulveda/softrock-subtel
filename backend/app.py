def current_user(request: Request) -> dict:
    con = db()
    try:
        auth = request.headers.get("authorization", "")
        if auth.lower().startswith("bearer "):
            th = hashlib.sha256(auth[7:].strip().encode()).hexdigest()
            row = con.execute("SELECT t.id, t.name, u.role FROM api_tokens t JOIN users u ON u.id=t.created_by "
                              "WHERE t.token_hash=? AND t.active=1 AND u.active=1", (th,)).fetchone()
            if not row:
                raise HTTPException(401, "Token de API inválido")
            con.execute("UPDATE api_tokens SET last_used_at=? WHERE id=?", (now(), row["id"]))
            con.commit()
            return {"id": None, "username": f"api:{row['name']}", "display_name": row["name"], "role": "operador", "api": True}
        tok = request.cookies.get("session")
        if tok:
            row = con.execute("SELECT u.* FROM sessions s JOIN users u ON u.id=s.user_id WHERE s.token=? AND s.expires>? AND u.active=1",
                              (tok, time.time())).fetchone()
            if row:
                return {"id": row["id"], "username": row["username"], "display_name": row["display_name"], "role": row["role"], "api": False}
        raise HTTPException(401, "No autenticado")
    finally:
        con.close()


def require(*roles):
    def dep(user: dict = Depends(current_user)):
        if roles and user["role"] not in roles:
            raise HTTPException(403, "Sin permiso para esta acción")
        return user
    return dep


def ip_of(request: Request) -> str | None:
    return request.client.host if request.client else None


