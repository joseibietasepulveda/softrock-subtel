def hash_password(pw: str, salt: bytes | None = None) -> str:
    salt = salt or secrets.token_bytes(16)
    h = hashlib.scrypt(pw.encode(), salt=salt, n=2 ** 14, r=8, p=1)
    return salt.hex() + "$" + h.hex()


def check_password(pw: str, stored: str) -> bool:
    if not stored or "$" not in stored:  # usuarios LDAP no tienen hash local
        return False
    salt, h = stored.split("$")
    return hmac.compare_digest(hash_password(pw, bytes.fromhex(salt)).split("$")[1], h)


def now() -> str:
    """Hora operacional solicitada por SUBTEL: offset fijo UTC-3."""
    return datetime.now(UTC_MINUS_3).isoformat(timespec="seconds")


