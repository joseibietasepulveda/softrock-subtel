async def change_own_password(request: Request, body: dict, user=Depends(current_user)):
    if user["api"]:
        raise HTTPException(403, "No aplica a tokens de API")
    current, new = body.get("current", ""), body.get("password", "")
    # Doble digitación (la UI pide dos veces cada contraseña). Si un cliente de API
    # no envía las confirmaciones, se asumen iguales y el comportamiento no cambia.
    if body.get("current_confirm", current) != current:
        raise HTTPException(400, "Las dos contraseñas actuales no coinciden")
    if body.get("password_confirm", new) != new:
        raise HTTPException(400, "Las dos contraseñas nuevas no coinciden")
    con = db()
    row = con.execute("SELECT password_hash FROM users WHERE id=?", (user["id"],)).fetchone()
    if not check_password(current, row["password_hash"]):
        con.close()
        raise HTTPException(400, "Contraseña actual incorrecta")
    _validate_password(new)
    con.execute("UPDATE users SET password_hash=? WHERE id=?", (hash_password(new), user["id"]))
    audit(con, user["username"], ip_of(request), "password_changed", {})
    con.close()
    return {"ok": True}


